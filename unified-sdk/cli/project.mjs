import { existsSync, readFileSync, realpathSync, readdirSync } from "node:fs";
import path from "node:path";
import { patchEntry, hasManualMount } from "./transform.mjs";

export const marker = "// Generated by unified-sdk setup.";
export const sdkVersion = JSON.parse(
  readFileSync(new URL("../package.json", import.meta.url), "utf8"),
).version;
const read = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);
function inside(root, file) {
  const relative = path.relative(root, file);
  return (
    relative !== ".." &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}
export function safeTarget(root, relative) {
  const file = path.resolve(root, relative);
  if (!inside(root, file))
    throw new Error("All setup files must be inside the target project.");
  let ancestor = file;
  while (!existsSync(ancestor)) ancestor = path.dirname(ancestor);
  if (!inside(root, realpathSync(ancestor)))
    throw new Error(
      "Setup will not write through a symlink outside the project.",
    );
  return file;
}
function selectEntry(root, pkg, explicit) {
  if (explicit) {
    const file = safeTarget(root, explicit);
    if (!existsSync(file)) throw new Error(`Entry not found: ${explicit}`);
    const normalized = path.relative(root, file).split(path.sep).join("/");
    return {
      file,
      framework: /(^|\/)app\/.*layout\.[jt]sx?$/.test(normalized)
        ? "next-app"
        : /(^|\/)pages\/_app\.[jt]sx?$/.test(normalized)
          ? "next-pages"
          : "vite",
    };
  }
  const next = pkg.dependencies?.next || pkg.devDependencies?.next;
  const candidates = next
    ? [
        "src/app/layout.tsx",
        "src/app/layout.jsx",
        "src/app/layout.js",
        "app/layout.tsx",
        "app/layout.jsx",
        "app/layout.js",
        "src/pages/_app.tsx",
        "src/pages/_app.jsx",
        "src/pages/_app.js",
        "pages/_app.tsx",
        "pages/_app.jsx",
        "pages/_app.js",
      ]
    : [
        "src/main.tsx",
        "src/main.jsx",
        "src/main.js",
        "src/index.tsx",
        "src/index.jsx",
        "src/index.js",
      ];
  const entry = candidates.find((file) => existsSync(path.join(root, file)));
  if (!entry)
    throw new Error(
      "Could not find a React entry. Use --entry for your Vite entry, Next root layout, or pages/_app file.",
    );
  return selectEntry(root, pkg, entry);
}
export function packageManager(root, pkg, override) {
  const manager =
    override ||
    pkg.packageManager?.split("@")[0] ||
    (existsSync(path.join(root, "pnpm-lock.yaml"))
      ? "pnpm"
      : existsSync(path.join(root, "yarn.lock"))
        ? "yarn"
        : ["bun.lock", "bun.lockb"].some((file) =>
              existsSync(path.join(root, file)),
            )
          ? "bun"
          : "npm");
  if (!["npm", "pnpm", "yarn", "bun"].includes(manager))
    throw new Error("Choose npm, pnpm, yarn, or bun with --package-manager.");
  return manager;
}
export function createPlan({
  cwd = process.cwd(),
  projectId,
  theme = "auto",
  apiUrl,
  entry,
  manager,
}) {
  for (const [name, value] of [
    ["project", projectId],
  ])
    if (typeof value !== "string" || !value.trim() || value.length > 200)
      throw new Error(`Provide --${name} from the project integration panel.`);
  if (!["auto", "project", "light", "dark"].includes(theme))
    throw new Error("Theme must be auto, project, light, or dark.");
  if (apiUrl && !/^https?:\/\/[^\s]+$/.test(apiUrl)) throw new Error("Provide an http(s) --api-url.");
  const root = realpathSync(cwd);
  const manifestFile = safeTarget(root, "package.json");
  const manifest = read(manifestFile);
  if (!manifest)
    throw new Error(
      "Run setup inside a React project with a package.json file.",
    );
  const pkg = JSON.parse(manifest);
  if (!pkg.dependencies?.react && !pkg.devDependencies?.react)
    throw new Error(
      "This package does not declare React. Select your React app with --cwd.",
    );
  const target = selectEntry(root, pkg, entry);
  if (!/\.[jt]sx?$/.test(target.file))
    throw new Error("The entry must be JavaScript or TypeScript.");
  const component = safeTarget(
    root,
    `${existsSync(path.join(root, "src")) ? "src/" : ""}components/unified-feedback-widget.${/\.tsx?$/.test(target.file) ? "tsx" : "jsx"}`,
  );
  const beforeComponent = read(component);
  if (beforeComponent !== null && !beforeComponent.includes(marker))
    throw new Error(
      "The widget file already exists and is not managed by this CLI. No files were changed.",
    );
  let componentImport = path
    .relative(path.dirname(target.file), component)
    .split(path.sep)
    .join("/")
    .replace(/\.[jt]sx$/, "");
  if (!componentImport.startsWith("."))
    componentImport = `./${componentImport}`;
  let count = 0;
  function checkExisting(directory) {
    for (const item of readdirSync(directory, { withFileTypes: true })) {
      if (
        item.name.startsWith(".") ||
        ["node_modules", "dist", "build", "coverage", "cli", "tests"].includes(
          item.name,
        ) ||
        item.isSymbolicLink()
      )
        continue;
      const file = path.join(directory, item.name);
      if (item.isDirectory()) checkExisting(file);
      else if (/\.[jt]sx?$/.test(file) && file !== component) {
        if (++count > 5000)
          throw new Error(
            "This folder is too large to scan safely. Select the app directory with --cwd.",
          );
        const source = readFileSync(file, "utf8");
        if (!source.includes("unified-sdk")) continue;
        let manual = false;
        try {
          manual = hasManualMount(source);
        } catch {
          continue;
        }
        if (manual)
          throw new Error(
            `UnifiedFeedback is already mounted manually in ${path.relative(root, file)}. No files were changed.`,
          );
      }
    }
  }
  checkExisting(root);
  const beforeEntry = read(target.file);
  const afterEntry = patchEntry(beforeEntry, {
    framework: target.framework,
    componentImport,
  });
  const props = {
    projectId: projectId.trim(),
    ...(apiUrl ? { apiUrl: apiUrl.replace(/\/$/, "") } : {}),
    ...(theme === "auto" ? {} : { theme }),
  };
  const generated = `"use client";\n${marker}\nimport { createElement } from "react";\nimport { UnifiedFeedback } from "unified-sdk";\n\nexport default function UnifiedFeedbackWidget() {\n  return createElement(UnifiedFeedback, ${JSON.stringify(props, null, 2).replace(/\n/g, "\n  ")});\n}\n`;
  pkg.dependencies = {
    ...pkg.dependencies,
    "unified-sdk": /^(file:|link:|workspace:)/.test(
      pkg.dependencies?.["unified-sdk"] || "",
    )
      ? pkg.dependencies["unified-sdk"]
      : `^${sdkVersion}`,
  };
  if (pkg.devDependencies?.["unified-sdk"])
    delete pkg.devDependencies["unified-sdk"];
  const indent = /\n([\t ]+)"/.exec(manifest)?.[1] || "  ";
  const files = [
    { path: target.file, before: beforeEntry, after: afterEntry },
    { path: component, before: beforeComponent, after: generated },
    {
      path: manifestFile,
      before: manifest,
      after: `${JSON.stringify(pkg, null, indent)}\n`,
    },
  ].filter((file) => file.before !== file.after);
  return {
    root,
    framework: target.framework,
    manager: packageManager(root, pkg, manager),
    files,
    component,
    entry: target.file,
  };
}
